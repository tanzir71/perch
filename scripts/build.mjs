import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { minify } from "terser";

const dashboard = await readFile(new URL("../stats/index.html", import.meta.url), "utf8");
const dashboardModule = `// Generated by scripts/build.mjs. Do not edit directly.\nexport default ${JSON.stringify(dashboard)};\n`;

await mkdir(new URL("../dist/", import.meta.url), { recursive: true });
await writeFile(new URL("../worker/dashboard.generated.js", import.meta.url), dashboardModule);

const tracker = await readFile(new URL("../src/perch.js", import.meta.url), "utf8");
const minified = await minify(tracker, {
  compress: {
    passes: 2
  },
  mangle: true,
  format: {
    comments: false
  }
});

if (!minified.code) {
  throw new Error("Tracker minification produced no output.");
}

await writeFile(new URL("../src/perch.min.js", import.meta.url), `${minified.code}\n`);

await build({
  entryPoints: [fileURLToPath(new URL("../worker/worker.js", import.meta.url))],
  outfile: fileURLToPath(new URL("../dist/worker.js", import.meta.url)),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "none"
});

const pagesOutput = new URL("../dist/pages/", import.meta.url);
await rm(pagesOutput, { recursive: true, force: true });
await mkdir(pagesOutput, { recursive: true });
await cp(new URL("../site/index.html", import.meta.url), new URL("index.html", pagesOutput));
await cp(new URL("../src/perch.min.js", import.meta.url), new URL("perch.min.js", pagesOutput));

console.log("Built tracker, Worker, and GitHub Pages artifact");
