import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { minify } from "terser";

const file = (path) => new URL(`../${path}`, import.meta.url);
const generated = (value) => `// Generated by scripts/build.mjs. Do not edit directly.\nexport default ${JSON.stringify(value)};\n`;

// 1. Tracker: minify once, ship it from GitHub Pages and from the Worker (/perch.js).
const tracker = await readFile(file("src/perch.js"), "utf8");
const minified = await minify(tracker, {
  compress: { passes: 2 },
  mangle: true,
  format: { comments: false }
});
if (!minified.code) throw new Error("Tracker minification produced no output.");
const trackerMin = `${minified.code}\n`;
await writeFile(file("src/perch.min.js"), trackerMin);
await writeFile(file("worker/tracker.generated.js"), generated(trackerMin));

// 2. Dashboard: inlined into the Worker so GET / serves it.
const dashboard = await readFile(file("stats/index.html"), "utf8");
await writeFile(file("worker/dashboard.generated.js"), generated(dashboard));

// 3. Worker bundle (used by the Miniflare integration test; Wrangler bundles worker/worker.js itself).
await mkdir(file("dist/"), { recursive: true });
await build({
  entryPoints: [fileURLToPath(file("worker/worker.js"))],
  outfile: fileURLToPath(file("dist/worker.js")),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "none"
});

// 4. GitHub Pages artifact.
await import("./build-pages.mjs");

console.log("Built tracker, Worker, and GitHub Pages artifact");
